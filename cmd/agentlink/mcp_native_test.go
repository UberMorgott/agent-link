package main

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"
)

// nativeToolsFile is the tool list of Claude Code's in-process module.
const nativeToolsFile = "../../plugins/agent-link/hooks/tools.gen.ts"

// updateNativeTools, when set to 1, makes TestNativeToolsMatchMCP write the
// file instead of comparing it.
const updateNativeTools = "AGENTLINK_UPDATE_NATIVE_TOOLS"

// Claude Code's in-process module (plugins/agent-link/hooks) serves the tools
// of `agentlink mcp` without the MCP process: the same names, descriptions
// and input schemas, generated from this server's own list. A tool added or
// changed here fails this test until the file is generated again:
//
//	AGENTLINK_UPDATE_NATIVE_TOOLS=1 go test ./cmd/agentlink -run TestNativeToolsMatchMCP
func TestNativeToolsMatchMCP(t *testing.T) {
	res, err := mcpClient(t, "127.0.0.1:1").ListTools(t.Context(), nil)
	if err != nil {
		t.Fatal(err)
	}
	type spec struct {
		Name        string `json:"name"`
		Description string `json:"description"`
		InputSchema any    `json:"inputSchema"`
	}
	var specs []spec
	for _, tool := range res.Tools {
		specs = append(specs, spec{Name: tool.Name, Description: tool.Description, InputSchema: tool.InputSchema})
	}
	slices.SortFunc(specs, func(a, b spec) int { return strings.Compare(a.Name, b.Name) })
	var list bytes.Buffer
	enc := json.NewEncoder(&list)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(specs); err != nil {
		t.Fatal(err)
	}
	want := "// Code generated by TestNativeToolsMatchMCP (cmd/agentlink/mcp_native_test.go); DO NOT EDIT.\n" +
		"// The tools of `agentlink mcp` (cmd/agentlink/mcp.go), as this module registers them.\n" +
		"import type { ToolSpec } from 'claude-code'\n\n" +
		"export const TOOLS: readonly ToolSpec[] = " + strings.TrimSpace(list.String()) + "\n"
	path := filepath.FromSlash(nativeToolsFile)
	if os.Getenv(updateNativeTools) == "1" {
		if err := os.WriteFile(path, []byte(want), 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path) //nolint:gosec // G304: the repository's plugin file
	if err != nil {
		t.Fatal(err)
	}
	if strings.ReplaceAll(string(got), "\r\n", "\n") != want {
		t.Fatalf("%s is not the MCP server's tool list: run this test with %s=1", nativeToolsFile, updateNativeTools)
	}
	if len(specs) != 9 {
		t.Fatalf("%d tools; the module's tests name nine", len(specs))
	}
}
